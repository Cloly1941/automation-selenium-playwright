package javaBasic;

public class Topic_04_Properties {
    static void main(String[] args) {
        System.out.println(System.getProperty("os.name")); // Tên hệ điều hành
        System.out.println(System.getProperty("user.dir")); // Thư mục làm việc hiện tại
        System.out.println(System.getProperty("java.version")); // Phiên bản Java đang chạy

        // Windows 11
        // C:\Users\Admin\IdeaProjects\MyProject
        // 21.0.2
    }
}

